fn main() {
    // 元组是一种异构有限序列，异构是指元组内的元素可以是不同类型，有限是指元组的长度是固定的
    // 语法：let t: (type1, type2, type3...) = (val1, val2, val3...);
    // 将类型放在()内，每个类型之间用逗号隔开，这就是元组的类型
    let tuple: (i32, f64, bool) = (100, 3.14, true);
    println!("第一个元素: {}", tuple.0); // 100
    println!("第二个元素: {}", tuple.1); // 3.14
    println!("第三个元素: {}", tuple.2); // true
    // 元组中，最后一个元素末尾可以携带逗号，这是其它语言比较少见的设计。
    // 不论是元组的值，还是元组的类型，最后一个逗号都可以保留。在后续的结构体等地方，也有类似的设计。
    let _: (i32, f64, bool) = (100, 3.14, true);
    let _: (i32, f64, bool) = (100, 3.14, true);
    let _: (i32, f64, bool) = (100, 3.14, true);
    let _: (i32, f64, bool) = (100, 3.14, true);
    // 多元素元组中，最后一个元素末尾可选携带逗号，结构体也类似
    // 不论是元组的值，还是元组的类型，最后一个逗号都可以保留
    // 只有一个元素的元组必须加一个逗号，否则它会被当作普通的括号表达式
    let t = (10,);
    println!("{:?}", t);
    // 模式匹配解构
    let point = (10, 20);
    let (x, y) = point; // 解构元组
    println!("坐标: x={}, y={}", x, y); // 坐标: x=10, y=20
    // 可以通过下划线 _ 来跳过某些元素实现跳过某些值的匹配
    // 以下忽略了元组中第二个元素，只提取第一个和第三个元素
    let (first, _, third) = (1, "hello", true);
    println!("first={}, third={}", first, third); // first=1, third=true
    // 单元类型（空元组）是一个特殊的元组类型，表示没有值的类型，写作 ()，它是所有函数的默认返回类型
    // 不带任何值的元组有一个特殊名字，叫做 单元（unit）。这种值以及其对应的类型都写作 ()，表示空值或空的返回类型
    // 如果一个表达式没有返回任何其他值，它就会隐式返回单元值
    // 它占用0字节，在内存中不实际存在
    let unit = ();
    println!("{:?}", unit);
    // 元组可以作为函数的返回值
    let result = tuple_func();
    println!("{:?}", result);
}

fn tuple_func() -> (&'static str,) {
    match rand::random::<u32>() % 5 + 1 {
        1 => ("one",),
        2 => ("two",),
        3 => ("three",),
        4 => ("four",),
        5 => ("five",),
        _ => ("unknown",),
    }
}
